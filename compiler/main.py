"""
MiniL Compiler CLI:
Compiles MiniL source files (.minil) to MiniL bytecode (.mbc).
"""
import argparse
import sys
import os
from compiler.lexer import Lexer
from compiler.parser import Parser
from compiler.sema import Sema
from compiler.analysis import IntervalAnalysis
from compiler.hoisting import HoistingPlanner
from compiler.codegen import CodeGenerator
from compiler.disasm import disassemble_file

def compile_source(source_code: str, mode: str = "R", safe_sites=None, report_path=None):
    # 1. Lexical Analysis
    lexer = Lexer(source_code)
    tokens = lexer.tokenize()

    # 2. Parsing
    parser = Parser(tokens)
    ast = parser.parse()

    # 3. Semantic Analysis
    sema = Sema()
    sema.analyze(ast)

    # 4. Static Safety Analysis (if mode in S, H, FS, FH)
    analysis = None
    hoisting_res = None
    target_ast = ast

    if mode in ("S", "H", "FS", "FH") and safe_sites is None:
        analysis = IntervalAnalysis(sema)
        report = analysis.analyze(ast)
        safe_sites = analysis.get_safe_sites()
        if report_path:
            import json
            with open(report_path, "w") as rf:
                json.dump(report, rf, indent=2)

    # 5. Loop-Guard Hoisting (if mode in H, FH)
    if mode in ("H", "FH"):
        planner = HoistingPlanner(sema)
        hoisting_res = planner.plan_and_transform(ast, safe_sites if safe_sites is not None else set())
        target_ast = hoisting_res.transformed_ast
        safe_sites = hoisting_res.safe_sites

    # 6. Code Generation
    codegen = CodeGenerator(sema, mode=mode, safe_sites=safe_sites)
    codegen.generate(target_ast)

    return codegen, sema, analysis

def main():
    arg_parser = argparse.ArgumentParser(description="MiniL Language Compiler")
    arg_parser.add_argument("source", help="Path to MiniL source code file (.minil)")
    arg_parser.add_argument("-o", "--output", help="Path to output bytecode file (.mbc)")
    arg_parser.add_argument("--mode", choices=["U", "R", "F", "S", "H", "FS", "FH"], default="R",
                            help="Bounds checking compilation mode (default: R)")
    arg_parser.add_argument("--report", help="Path to output analysis report (.json)")
    arg_parser.add_argument("--disasm", action="store_true", help="Print disassembly of generated bytecode")

    args = arg_parser.parse_args()

    with open(args.source, "r") as f:
        source_code = f.read()

    output_path = args.output
    if not output_path:
        stem, _ = os.path.splitext(args.source)
        output_path = stem + ".mbc"

    try:
        codegen, sema, analysis = compile_source(source_code, mode=args.mode, report_path=args.report)
        codegen.write_bytecode(output_path)
    except Exception as e:
        sys.stderr.write(f"Compilation error: {e}\n")
        sys.exit(1)

    if args.disasm:
        disassemble_file(output_path)

if __name__ == "__main__":
    main()
