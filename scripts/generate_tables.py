#!/usr/bin/env python3
"""
Task 11: LaTeX Table Generator.
Reads raw and summary CSVs from results/ and generates clean, booktabs-formatted
LaTeX table snippets in results/tables/*.tex with consistent rounding.
"""
import csv
import json
import math
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLES_DIR = os.path.join(REPO_ROOT, "results", "tables")
os.makedirs(TABLES_DIR, exist_ok=True)

def generate_timing_table():
    summary_path = os.path.join(REPO_ROOT, "results", "timing_summary.csv")
    if not os.path.exists(summary_path):
        return

    data = {}
    with open(summary_path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            b = row["benchmark"]
            m = row["mode"]
            if b not in data:
                data[b] = {}
            ovh = float(row.get("overhead_pct") or row.get("median_overhead_pct", 0.0))
            low = float(row.get("ci_low_pct") or row.get("ci_lower_pct", 0.0))
            high = float(row.get("ci_high_pct") or row.get("ci_upper_pct", 0.0))
            data[b][m] = (ovh, low, high)

    out_path = os.path.join(TABLES_DIR, "timing_summary.tex")
    with open(out_path, "w") as f:
        f.write("% Auto-generated by scripts/generate_tables.py\n")
        f.write("\\begin{tabular}{lrrrrrr}\n")
        f.write("\\toprule\n")
        f.write("Benchmark & Mode R (\\%) & Mode F (\\%) & Mode S (\\%) & Mode H (\\%) & Mode FS (\\%) & Mode FH (\\%) \\\\\n")
        f.write("\\midrule\n")

        geomean_data = {m: [] for m in ["R", "F", "S", "H", "FS", "FH"]}

        for b in sorted(data.keys()):
            cols = []
            for m in ["R", "F", "S", "H", "FS", "FH"]:
                ovh, low, high = data[b].get(m, (0.0, 0.0, 0.0))
                cols.append(f"{ovh:+.2f}")
                if b != "fib":
                    geomean_data[m].append(1.0 + ovh / 100.0)
            f.write(f"{b.replace('_', '\\_')} & " + " & ".join(cols) + " \\\\\n")

        f.write("\\midrule\n")
        geomean_cols = []
        for m in ["R", "F", "S", "H", "FS", "FH"]:
            vals = geomean_data[m]
            if vals:
                gm = math.exp(sum(math.log(max(x, 1e-6)) for x in vals) / len(vals))
                gm_ovh = (gm - 1.0) * 100.0
                geomean_cols.append(f"\\textbf{{{gm_ovh:+.2f}}}")
            else:
                geomean_cols.append("---")
        f.write("\\textbf{Geomean (excl. fib)} & " + " & ".join(geomean_cols) + " \\\\\n")
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
    print(f"Generated {out_path}")

def generate_static_counts_table():
    path = os.path.join(REPO_ROOT, "results", "static_counts.csv")
    if not os.path.exists(path):
        return

    out_path = os.path.join(TABLES_DIR, "static_counts.tex")
    with open(out_path, "w") as out_f, open(path) as in_f:
        reader = csv.DictReader(in_f)
        out_f.write("% Auto-generated by scripts/generate_tables.py\n")
        out_f.write("\\begin{tabular}{lrrrrr}\n")
        out_f.write("\\toprule\n")
        out_f.write("Benchmark & Total Sites & Safe (Mode S) & Hoisted (Mode H) & Residual (H) & Elim. Rate (\\%) \\\\\n")
        out_f.write("\\midrule\n")

        tot_sites = 0
        tot_safe = 0
        tot_hoisted = 0
        tot_residual = 0

        for row in reader:
            b = row["benchmark"]
            t = int(row["all_sites"])
            s = int(row["safe_sites"])
            h = int(row["hoisted_sites"])
            r = int(row["residual_sites"])
            elim_pct = ((s + h) / t * 100.0) if t > 0 else 0.0

            tot_sites += t
            tot_safe += s
            tot_hoisted += h
            tot_residual += r

            out_f.write(f"{b.replace('_', '\\_')} & {t} & {s} & {h} & {r} & {elim_pct:.1f}\\% \\\\\n")

        out_f.write("\\midrule\n")
        tot_elim = ((tot_safe + tot_hoisted) / tot_sites * 100.0) if tot_sites > 0 else 0.0
        out_f.write(f"\\textbf{{Total}} & \\textbf{{{tot_sites}}} & \\textbf{{{tot_safe}}} & \\textbf{{{tot_hoisted}}} & \\textbf{{{tot_residual}}} & \\textbf{{{tot_elim:.1f}\\%}} \\\\\n")
        out_f.write("\\bottomrule\n")
        out_f.write("\\end{tabular}\n")
    print(f"Generated {out_path}")

def generate_dynamic_counts_table():
    path = os.path.join(REPO_ROOT, "results", "dynamic_counts.csv")
    if not os.path.exists(path):
        return

    # Pivot dynamic counts: data[bench][mode] = (instr_count, check_count)
    data = {}
    with open(path) as in_f:
        reader = csv.DictReader(in_f)
        for row in reader:
            b = row["benchmark"]
            m = row["mode"]
            if b not in data:
                data[b] = {}
            data[b][m] = (int(row["instr_count"]), int(row["check_count"]))

    out_path = os.path.join(TABLES_DIR, "dynamic_counts.tex")
    with open(out_path, "w") as out_f:
        out_f.write("% Auto-generated by scripts/generate_tables.py\n")
        out_f.write("\\begin{tabular}{lrrrrr}\n")
        out_f.write("\\toprule\n")
        out_f.write("Benchmark & Checks (Mode R) & Checks (Mode S) & Checks (Mode H) & Checks (Mode FH) & Elim. (FH vs R) \\\\\n")
        out_f.write("\\midrule\n")

        tot_r = 0
        tot_s = 0
        tot_h = 0
        tot_fh = 0

        for b in sorted(data.keys()):
            r = data[b].get("R", (0, 0))[1]
            s = data[b].get("S", (0, 0))[1]
            h = data[b].get("H", (0, 0))[1]
            fh = data[b].get("FH", (0, 0))[1]
            elim_pct = ((r - fh) / r * 100.0) if r > 0 else 0.0

            tot_r += r
            tot_s += s
            tot_h += h
            tot_fh += fh

            out_f.write(f"{b.replace('_', '\\_')} & {r:,} & {s:,} & {h:,} & {fh:,} & {elim_pct:.1f}\\% \\\\\n")

        out_f.write("\\midrule\n")
        overall_elim = ((tot_r - tot_fh) / tot_r * 100.0) if tot_r > 0 else 0.0
        out_f.write(f"\\textbf{{Total}} & \\textbf{{{tot_r:,}}} & \\textbf{{{tot_s:,}}} & \\textbf{{{tot_h:,}}} & \\textbf{{{tot_fh:,}}} & \\textbf{{{overall_elim:.1f}\\%}} \\\\\n")
        out_f.write("\\bottomrule\n")
        out_f.write("\\end{tabular}\n")
    print(f"Generated {out_path}")

def generate_decomposition_table():
    path = os.path.join(REPO_ROOT, "results", "decomposition_summary.csv")
    if not os.path.exists(path):
        return

    out_path = os.path.join(TABLES_DIR, "decomposition.tex")
    with open(out_path, "w") as out_f, open(path) as in_f:
        reader = csv.DictReader(in_f)
        out_f.write("% Auto-generated by scripts/generate_tables.py\n")
        out_f.write("\\begin{tabular}{lrrrrrr}\n")
        out_f.write("\\toprule\n")
        out_f.write("Benchmark & R Ovhead (\\%) & N Ovhead (\\%) & F Ovhead (\\%) & FN Ovhead (\\%) & Dispatch Share (\\%) & Comp Share (\\%) \\\\\n")
        out_f.write("\\midrule\n")

        # Filter for GOTO configuration
        dispatch_shares = []
        comp_shares = []

        for row in reader:
            if row["config"] != "GOTO":
                continue
            b = row["benchmark"]
            r = float(row["r_overhead_pct"])
            n = float(row["n_overhead_pct"])
            f = float(row["f_overhead_pct"])
            fn = float(row["fn_overhead_pct"])
            d_share = float(row["dispatch_share_pct"])
            c_share = float(row["comp_share_pct"])
            dispatch_shares.append(d_share)
            comp_shares.append(c_share)

            out_f.write(f"{b.replace('_', '\\_')} & {r:+.2f} & {n:+.2f} & {f:+.2f} & {fn:+.2f} & {d_share:.1f} & {c_share:.1f} \\\\\n")

        out_f.write("\\midrule\n")
        mean_d = sum(dispatch_shares) / len(dispatch_shares) if dispatch_shares else 0.0
        mean_c = sum(comp_shares) / len(comp_shares) if comp_shares else 0.0
        out_f.write(f"\\textbf{{Mean}} & --- & --- & --- & --- & \\textbf{{{mean_d:.1f}\\%}} & \\textbf{{{mean_c:.1f}\\%}} \\\\\n")
        out_f.write("\\bottomrule\n")
        out_f.write("\\end{tabular}\n")
    print(f"Generated {out_path}")

def generate_dispatch_ablation_table():
    path = os.path.join(REPO_ROOT, "results", "dispatch_ablation_summary.csv")
    if not os.path.exists(path):
        return

    data = {}
    with open(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            cfg = row["config"]
            m = row["mode"]
            if cfg not in data:
                data[cfg] = {}
            data[cfg][m] = float(row["geomean_overhead_pct"])

    out_path = os.path.join(TABLES_DIR, "dispatch_ablation.tex")
    with open(out_path, "w") as f:
        f.write("% Auto-generated by scripts/generate_tables.py\n")
        f.write("\\begin{tabular}{lrrrrrrrr}\n")
        f.write("\\toprule\n")
        f.write("Dispatch Technique & R (\\%) & F (\\%) & S (\\%) & H (\\%) & FS (\\%) & FH (\\%) & N (\\%) & FN (\\%) \\\\\n")
        f.write("\\midrule\n")

        order = ["GOTO", "SWITCH", "DIRECT", "OPT3"]
        labels = {
            "GOTO": "Computed GOTO (-O2)",
            "SWITCH": "Switch Dispatch (-O2)",
            "DIRECT": "Direct-Threaded (-O2)",
            "OPT3": "Computed GOTO (-O3)"
        }

        for cfg in order:
            if cfg not in data:
                continue
            cols = []
            for m in ["R", "F", "S", "H", "FS", "FH", "N", "FN"]:
                val = data[cfg].get(m, 0.0)
                cols.append(f"{val:+.2f}")
            f.write(f"{labels[cfg]} & " + " & ".join(cols) + " \\\\\n")

        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
    print(f"Generated {out_path}")

def generate_fault_injection_table():
    path = os.path.join(REPO_ROOT, "results", "fault_injection_results.csv")
    if not os.path.exists(path):
        return

    by_op = {}
    with open(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            op = row["operator"]
            if op not in by_op:
                by_op[op] = {
                    "total": 0, "faulty": 0, "benign": 0,
                    "def_viol": 0, "more_alarms": 0, "silent_u": 0
                }
            by_op[op]["total"] += 1
            if row.get("classification") == "faulty":
                by_op[op]["faulty"] += 1
            else:
                by_op[op]["benign"] += 1

            finding = row.get("static_finding", "")
            if finding == "definite_violation":
                by_op[op]["def_viol"] += 1
            elif finding == "new_alarm":
                by_op[op]["more_alarms"] += 1

            if row.get("u_behavior") == "silent_corrupt":
                by_op[op]["silent_u"] += 1

    out_path = os.path.join(TABLES_DIR, "fault_injection.tex")
    with open(out_path, "w") as f:
        f.write("% Auto-generated by scripts/generate_tables.py\n")
        f.write("\\begin{tabular}{lrrrrrr}\n")
        f.write("\\toprule\n")
        f.write("Mutation Operator & Mutants & Faulty (Trapped) & Benign & Compile-time Viol. & Static Alarms & Silent U Corrupt. \\\\\n")
        f.write("\\midrule\n")

        tot = {k: 0 for k in ["total", "faulty", "benign", "def_viol", "more_alarms", "silent_u"]}

        for op, counts in sorted(by_op.items()):
            for k in tot:
                tot[k] += counts[k]
            f.write(f"{op} & {counts['total']} & {counts['faulty']} & {counts['benign']} & {counts['def_viol']} & {counts['more_alarms']} & {counts['silent_u']} \\\\\n")

        f.write("\\midrule\n")
        f.write(f"\\textbf{{Total}} & \\textbf{{{tot['total']}}} & \\textbf{{{tot['faulty']}}} & \\textbf{{{tot['benign']}}} & \\textbf{{{tot['def_viol']}}} & \\textbf{{{tot['more_alarms']}}} & \\textbf{{{tot['silent_u']}}} \\\\\n")
        f.write("\\bottomrule\n")
        f.write("\\end{tabular}\n")
    print(f"Generated {out_path}")

def main():
    generate_timing_table()
    generate_static_counts_table()
    generate_dynamic_counts_table()
    generate_decomposition_table()
    generate_dispatch_ablation_table()
    generate_fault_injection_table()
    print("All LaTeX tables generated successfully!")

if __name__ == "__main__":
    main()
